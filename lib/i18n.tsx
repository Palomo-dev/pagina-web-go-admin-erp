export function LanguageProvider({ children }: { children: ReactNode }) {
  // El sitio nuevo está en español (Manual › 01: "Desde Colombia") y no tiene selector de idioma.
  // Las páginas heredadas se fijan en español para no mezclar idiomas con la navegación nueva.
  const [lang, setLangState] = useState<Language>("es")

  const setLang = (newLang: Language) => {
    setLangState(newLang)
  }

  const t = (key: string): string => {
    return translations[lang][key] || key
  }

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) {
    throw new Error("useLanguage must be used within a LanguageProvider")
  }
  return context
}

/**
 * Hook for page-level bilingual content.
 * Define ES/EN content inline in each page component.
 * Returns the content object for the current language.
 */
export function useContent<T>(content: Record<Language, T>): T {
  const { lang } = useLanguage()
  return content[lang]
}
